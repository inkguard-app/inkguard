"""Build inkguard/lexicon_rare.py: rare-disease names for the review workflow's
flags (the review workflow is in development, not part of 0.25.0).

Source: MONDO Disease Ontology (CC BY 4.0): classes Orphanet counts as rare
(fewer than 1 in 2,000 people) that at least one other rare-disease source
(GARD, NORD, DOID, NCIt, MONDO's own curation) also lists, and that are
single diseases, not groupings; their labels and EXACT synonyms. MONDO's
broad "rare" subset alone flagged carpal tunnel syndrome and osteomyelitis
in 11% of the test notes: a flag on everything is a flag nobody reads.

A rare diagnosis is not an identifier by itself, but beside a town, an age
or a job it is how a patient in redacted notes gets recognised. The review
page flags it so both reviewers look at the combination.

    python tools/build_rare_diseases.py [/path/to/vocab_src]
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RARE_SOURCES = {"orphanet_rare", "gard_rare", "nord_rare", "doid_rare", "ncit_rare",
                "mondo_curated_rare"}
_SYN = re.compile(r'^synonym: "((?:[^"\\]|\\.)*)" (EXACT|RELATED|NARROW|BROAD)')


def norm(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", " ", s.lower()).strip()


def rare_terms(path: Path) -> tuple[set[str], int]:
    phrases: set[str] = set()
    classes = 0
    cur = None

    def flush():
        nonlocal classes
        if (cur and "orphanet_rare" in cur["subs"] and "disease_grouping" not in cur["subs"]
                and len(cur["subs"] & RARE_SOURCES) >= 2
                and not cur["obsolete"] and cur["id"].startswith("MONDO:")):
            classes += 1
            for s in [cur["name"], *cur["syn"]]:
                if s:
                    phrases.add(norm(s))

    for line in open(path, encoding="utf-8"):
        if line.startswith("[Term]"):
            flush()
            cur = {"id": "", "name": "", "syn": [], "subs": set(), "obsolete": False}
            continue
        if line.startswith("["):
            flush()
            cur = None
            continue
        if cur is None:
            continue
        if line.startswith("id: "):
            cur["id"] = line[4:].strip()
        elif line.startswith("name: "):
            cur["name"] = line[6:].strip()
        elif line.startswith("subset: "):
            cur["subs"].add(line.split()[1])
        elif line.startswith("is_obsolete: true"):
            cur["obsolete"] = True
        else:
            m = _SYN.match(line)
            if m and m.group(2) == "EXACT":
                cur["syn"].append(m.group(1).replace('\\"', '"'))
    flush()
    return phrases, classes


def keep(p: str) -> bool:
    """Phrases a note could contain and that mean the rare disease only."""
    if len(p) < 6 or not re.search(r"[a-z]{3}", p):
        return False
    words = p.split()
    if len(words) == 1:
        try:
            from wordfreq import zipf_frequency
            if zipf_frequency(p, "en") >= 3.0:       # "gout" is not rare; nor is "anemia"
                return False
        except Exception:
            pass
    # Bare type numbers and gene-symbol-only synonyms read like codes.
    if re.fullmatch(r"[a-z]{1,6} ?\d+[a-z]?", p):
        return False
    return len(words) <= 10


def main() -> None:
    src = Path(sys.argv[1] if len(sys.argv) > 1 else "vocab_src")
    phrases, classes = rare_terms(src / "mondo.obo")
    kept = sorted(p for p in phrases if keep(p))
    out = ROOT / "inkguard" / "lexicon_rare.py"
    with open(out, "w") as fh:
        fh.write('"""GENERATED by tools/build_rare_diseases.py — do not edit.\n\n'
                 "Rare-disease names: labels and exact synonyms of MONDO classes that\n"
                 "Orphanet and one more rare-disease source list, groupings excluded,\n"
                 "normalised to lowercase words. MONDO Disease Ontology,\n"
                 "CC BY 4.0. Used only to flag a note for the two reviewers.\n"
                 '"""\n')
        fh.write("RARE_DISEASES = frozenset((\n")
        for p in kept:
            fh.write(f"    {p!r},\n")
        fh.write("))\n")
        fh.write(f"MAX_WORDS = {max(len(p.split()) for p in kept)}\n")
    print(f"rare classes {classes}; phrases {len(phrases)}; kept {len(kept)}")
    for probe in ("achondroplasia", "cystic fibrosis", "gout", "fabry disease",
                  "huntington disease", "diabetes mellitus", "breast cancer", "asthma",
                  "carpal tunnel syndrome", "osteomyelitis", "renal cell carcinoma"):
        print(f"  {probe}: {'yes' if norm(probe) in set(kept) else 'no'}")


def _pack() -> None:
    """Store the list as data (inkguard/data/lexicon_rare.json.gz) with a short loader."""
    import sys as _sys
    from pathlib import Path as _P
    _sys.path.insert(0, str(_P(__file__).resolve().parents[1]))
    from inkguard._data import pack_module
    pack_module("lexicon_rare", "tools/build_rare_diseases.py")


if __name__ == "__main__":
    main()
    _pack()
