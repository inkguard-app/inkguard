#!/usr/bin/env python3
"""
Build inkguard/lexicon_english.py — ordinary English words that are NOBODY'S
NAME in any list we hold.

Why: words such as "Disheveled" (MSE), "Outpatient" (follow-up) and
"Graft" (op note) are common in notes but rarer on the web than the 3.5
Zipf bar the engine uses to call something "a dictionary word", so they
were masked as [NAME]. WordNet knows them.

Source: WordNet 3.0 index files (Princeton; permissive licence with
notice, see THIRD_PARTY_NOTICES.md). Lowercase single-word lemmas only
(WordNet capitalises proper nouns), plus the adjective exception forms.

A word is DROPPED when it appears in ANY name list we hold, because a
surname that is also a word ("Baker", "Graves", "Rose") must never be
waved through as a word:
  - the tool's name registry
  - 1990 census surnames (dist.all.last) and first names
  - 2000 census surnames (census2000.csv)
  - the international surname and first-name lists
The cost of that rule is only that some words get no help from this list;
it never lets a name through.

  python tools/build_english_words.py SRC_DIR
"""
from __future__ import annotations

import csv
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))


def main() -> None:
    src = Path(sys.argv[1] if len(sys.argv) > 1 else "vocab_src")
    from inkguard.name_registry import NAMES
    names = set(NAMES)
    for f in ("dist.all.last", "dist.female.first", "dist.male.first"):
        p = src / f
        if p.exists():
            names |= {l.split()[0].lower() for l in open(p) if l.strip()}
    c = src / "census2000.csv"
    if c.exists():
        names |= {r["name"].lower() for r in csv.DictReader(open(c))}
    for f in ("intl_surnames.txt", "intl_first.txt"):
        p = src / f
        if p.exists():
            names |= {l.strip().lower() for l in open(p) if l.strip()}

    words: set[str] = set()
    wn = src / "wordnet"
    for pos in ("noun", "verb", "adj", "adv"):
        for line in open(wn / f"index.{pos}", encoding="latin-1"):
            if line.startswith(" "):
                continue
            lemma = line.split(" ", 1)[0]
            if lemma.isalpha() and lemma.islower() and len(lemma) >= 4:
                words.add(lemma)
    for exc in ("adj.exc", "noun.exc", "verb.exc"):
        for line in open(wn / exc, encoding="latin-1"):
            form = line.split(" ", 1)[0]
            if form.isalpha() and form.islower() and len(form) >= 4:
                words.add(form)
    # Regular past tenses of WordNet verbs ("paged", "notified"): a nurse's
    # entry often starts with one, capitalised. The -ed form is checked
    # against the name lists itself, so "page" (a surname) does not stop
    # "paged" (nobody's name).
    for line in open(wn / "index.verb", encoding="latin-1"):
        if line.startswith(" "):
            continue
        v = line.split(" ", 1)[0]
        if not (v.isalpha() and v.islower() and len(v) >= 3):
            continue
        if v.endswith("e"):
            words.add(v + "d")
        elif v.endswith("y") and v[-2:-1] not in "aeiou":
            words.add(v[:-1] + "ied")
        else:
            words.add(v + "ed")
    kept = sorted(words - names)
    out = ROOT / "inkguard" / "lexicon_english.py"
    with open(out, "w") as fh:
        fh.write('"""GENERATED by tools/build_english_words.py — do not edit.\n\n'
                 "Lowercase English words from WordNet 3.0 (Princeton, permissive licence\n"
                 "with notice) that are in NO name list the tool holds. Used only to\n"
                 "say 'this capitalised word is an ordinary word', never to find PHI.\n"
                 '"""\n')
        fh.write("_WORDS = (\n")
        for i in range(0, len(kept), 12):
            fh.write("    " + repr(" ".join(kept[i:i + 12]) + " ") + "\n")
        fh.write(")\n\nENGLISH_WORDS = frozenset(\"\".join(_WORDS).split())\n")
        # Dictionary words that are ALSO names ("stapler", "gauze", "rose").
        # The agate reads a LOWERCASE one in its dictionary
        # sense; detection never uses this list.
        also = sorted(words & names)
        fh.write("\n_ALSO = (\n")
        for i in range(0, len(also), 12):
            fh.write("    " + repr(" ".join(also[i:i + 12]) + " ") + "\n")
        fh.write(")\n\nNAME_ALSO_WORDS = frozenset(\"\".join(_ALSO).split())\n")
    print(f"wordnet lemmas {len(words)}; dropped as names {len(words) - len(kept)}; kept {len(kept)}")
    for w in ("disheveled", "outpatient", "graft", "postop", "baker", "graves", "rose", "paged", "notified", "reed"):
        print(f"  {w}: {'kept' if w in kept else 'not kept'}")


def _pack() -> None:
    """Store the list as data (inkguard/data/lexicon_english.json.gz) with a short loader."""
    import sys as _sys
    from pathlib import Path as _P
    _sys.path.insert(0, str(_P(__file__).resolve().parents[1]))
    from inkguard._data import pack_module
    pack_module("lexicon_english", "tools/build_english_words.py")


if __name__ == "__main__":
    main()
    _pack()
