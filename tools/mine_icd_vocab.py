import csv, re, collections, importlib, sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from wordfreq import zipf_frequency
"""Regenerate inkguard/lexicon_icd_vocab.py from the CMS ICD-10-CM code file.

Usage: python tools/mine_icd_vocab.py path/to/icd10cm_codes.csv CENSUS_DIR
CENSUS_DIR holds census2000.csv and the 1990 first-name files; if it is
left out, the current folder is used, and missing files are skipped.
Requires wordfreq.
"""
import sys
ICD_CSV = sys.argv[1] if len(sys.argv) > 1 else "icd10.csv"
lower = collections.Counter(); upper_mid=set()
for row in csv.reader(open(ICD_CSV)):
    # Chapters A-T only: V-Y are external causes (vehicles, animals,
    # places: "fluke", "saddle", "bomber") where surname collisions live.
    if not row[0] or row[0][0] > "T":
        continue
    for desc in (row[3], row[5]):
        toks = re.findall(r"[A-Za-z][A-Za-z'\-]+", desc)
        for i,t in enumerate(toks):
            if t[0].isupper() and i>0: upper_mid.add(t.lower())
            if t.islower() or (i == 0 and t[1:].islower()): lower[t.lower()]+=1
# NAME GUARD: the tool's name registry plus every 2000 US Census surname
# and the 1990 first names (tools/build_open_lexicon.load_census). A word that is
# anybody's name never enters the vocabulary.
from inkguard.name_registry import NAMES
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_open_lexicon import load_census
CENSUS_DIR = sys.argv[2] if len(sys.argv) > 2 else "."
names = set(NAMES) | load_census(CENSUS_DIR)
print("names", len(names))
from inkguard.clinical_lexicon import AMBIGUOUS_EPONYMS, _ALL_CLINICAL_TERMS
vocab=set()
for w,c in lower.items():
    if len(w)<5 or "'" in w: continue
    if w in names or w in AMBIGUOUS_EPONYMS or w in upper_mid: continue
    if zipf_frequency(w,'en')>=4.0: continue
    if w in _ALL_CLINICAL_TERMS: continue
    vocab.add(w)
print("vocab", len(vocab))
for probe in ['urethra','bladder','prostate','verumontanum','hernia','cystocele','rectocele','gallop','noncontributory','scrotum','testis','kidney','ureter']:
    print(probe, probe in vocab, probe in names, zipf_frequency(probe,'en'))
out=open("inkguard/lexicon_icd_vocab.py","w")
out.write('''"""
ICD-10-CM description vocabulary — GENERATED by tools/mine_icd_vocab.py.

Every lowercase word in the ICD-10-CM code descriptions, chapters A-T
(CMS, public domain; V-Y external-cause chapters excluded), minus:
  - any word that is a personal name in inkguard/name_registry.py or in the
    US Census name files (a surname must never become "clinical");
  - any word the existing lexicon files as an ambiguous eponym;
  - any word that ICD itself capitalizes mid-description (eponyms,
    genera, places);
  - general-English words at zipf >= 4.0 (common enough to be a surname
    somewhere, and already handled by the frequency layer).

What is left is organ, structure, lesion and procedure vocabulary —
"urethra", "cystocele", "scrotum": words that operative notes often open
sentences with, and that a name finder can mistake for surnames.
"""

ICD_VOCAB: frozenset[str] = frozenset({
''')
for w in sorted(vocab): out.write(f'    "{w}",\n')
out.write("})\n")
out.close()

